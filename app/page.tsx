import Link from "next/link";
import { Suspense } from "react";
import { DifficultyBadge, VerificationPill } from "@/components/badges";
import { GuideCard } from "@/components/GuideCard";
import { LibraryBrowser, type GuideInfo } from "@/components/LibraryBrowser";
import { LookupBox } from "@/components/LookupBox";
import { CATALOG } from "@/lib/catalog";
import { listLibraryGuides } from "@/lib/guide/library";
import { cardInfo } from "@/lib/guide/summary";
import { getStore } from "@/lib/store";

export default function Home() {
  const cards = listLibraryGuides().map(cardInfo);
  const guideInfo: Record<string, GuideInfo> = Object.fromEntries(
    cards.map((c) => [c.slug, { difficulty: c.difficulty, label: c.label, effort: c.effort, wait: c.wait }]),
  );

  return (
    <>
      <section className="border-b border-line bg-gradient-to-b from-emerald-50/60 to-transparent">
        <div className="mx-auto max-w-6xl px-4 py-14">
          <p className="text-sm font-medium text-emerald-700">For developers whose users connect apps to AI agents</p>
          <h1 className="mt-2 max-w-3xl text-4xl font-semibold tracking-tight sm:text-5xl">Know what it takes to get your OAuth app approved.</h1>
          <p className="mt-4 max-w-2xl text-lg text-zinc-600">
            Hands-on effort, the wait for provider review, who can connect before approval, what can block you, and which steps an agent can do for you.
            Every claim is marked as tested, documented, reported or inferred.
          </p>
          <div className="mt-7">
            <LookupBox />
          </div>
        </div>
      </section>

      <section className="mx-auto max-w-6xl px-4 py-10">
        <div className="mb-4 flex items-end justify-between gap-4">
          <div>
            <h2 className="text-xl font-semibold tracking-tight">From self-serve to gated</h2>
            <p className="text-sm text-zinc-600">
              {cards.length} researched guides ({cards.filter((c) => c.verification !== "unverified").length} fact-checked against their sources), sorted by how hard
              the access an agent integration usually needs is to get.
            </p>
          </div>
          <Link href="/method" className="hidden text-sm text-zinc-600 underline-offset-4 hover:underline sm:block">
            How these are made →
          </Link>
        </div>
        <div className="grid gap-4 sm:grid-cols-2 lg:grid-cols-3">
          {cards.map((c) => (
            <GuideCard key={c.slug} c={c} />
          ))}
        </div>
      </section>

      <Suspense fallback={null}>
        <RecentlyGenerated />
      </Suspense>

      <section id="library" className="mx-auto max-w-6xl px-4 py-10">
        <h2 className="text-xl font-semibold tracking-tight">Library: {CATALOG.length} OAuth apps</h2>
        <p className="mb-4 text-sm text-zinc-600">
          Apps without a ready guide are researched live: the agent reads the provider&apos;s docs, probes their OAuth endpoints and fact-checks its own draft.
        </p>
        <LibraryBrowser apps={CATALOG} guides={guideInfo} />
      </section>
    </>
  );
}

async function RecentlyGenerated() {
  const recent = await getStore().listGuides(9);
  if (recent.length === 0) return null;
  return (
    <section className="mx-auto max-w-6xl px-4 pb-2">
      <h2 className="text-xl font-semibold tracking-tight">Recently generated by the agent</h2>
      <ul className="mt-3 grid gap-2 sm:grid-cols-2 lg:grid-cols-3">
        {recent.map((r) => (
          <li key={r.slug}>
            <Link href={`/guides/${r.slug}`} className="flex items-center justify-between gap-2 rounded-lg border border-line bg-card px-3 py-2 text-sm hover:border-zinc-300">
              <span className="truncate font-medium">{r.name}</span>
              <span className="flex shrink-0 items-center gap-1.5">
                <DifficultyBadge level={r.difficulty} label={r.difficultyLabel} />
                <VerificationPill status={r.verification as "verified" | "partial" | "unverified"} />
              </span>
            </Link>
          </li>
        ))}
      </ul>
    </section>
  );
}
